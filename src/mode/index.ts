/** Name of the state file of a check in the temporary directory (04-REQ-49). */
export function checkStateFileName(runId: string): string {
  return `playwright-performance-regression-${runId}.check.json`;
}

/** Default of PW_PERF_MAX_TESTS and --max-tests (04-REQ-49). */
export const DEFAULT_MAX_TESTS = 10;

const POSITIVE_INTEGER = /^[1-9][0-9]*$/u;
const ENV_LABEL = /^[a-z0-9-]{1,32}$/u;

/**
 * Number of passes from the text of PW_PERF_PASSES or --passes: an integer >= 1, else null.
 * The upper bound comes from the config schema (resolveConfig, 04-REQ-06).
 */
export function parsePasses(text: string): number | null {
  return POSITIVE_INTEGER.test(text) ? Number(text) : null;
}

/** PW_PERF_PASS=k/N with 2 <= k <= N <= 1000 (01, chapter 6), else null. */
export function parsePass(text: string): { index: number; total: number } | null {
  const match = /^([1-9][0-9]*)\/([1-9][0-9]*)$/u.exec(text);
  if (match === null) return null;
  const index = Number(match[1]);
  const total = Number(match[2]);
  return index >= 2 && index <= total && total <= 1000 ? { index, total } : null;
}

/** Whether `text` is a valid environment label (PW_PERF_ENV, --env; D-18). */
export function isEnvLabel(text: string): boolean {
  return ENV_LABEL.test(text);
}

/** Expected format of a repetition count and of an environment label, for messages. */
export const PASSES_FORMAT = 'an integer >= 1, like "5"';
export const ENV_LABEL_FORMAT =
  'a label of lowercase letters, digits and "-" (at most 32 characters), like "staging"';

/**
 * Run id `YYYY-MM-DDTHH-MM-SS-xxxx`: start time in UTC and 4 random hex digits (04-REQ-10).
 * Generated by the CLI, or by the reporter when it runs without the CLI.
 */
export function generateRunId(date: Date, random: () => number): string {
  const time = date.toISOString().slice(0, 19).replaceAll(':', '-');
  const hex = Math.floor(random() * 0x10000)
    .toString(16)
    .padStart(4, '0');
  return `${time}-${hex}`;
}

/** An empty variable counts as unset (03, chapter 10). */
function read(env: ModeEnv, name: string): string | undefined {
  const value = env[name];
  return value === undefined || value === '' ? undefined : value;
}

function invalid(name: string, expected: string, value: string, hint: string): ModeIssue {
  return {
    code: 'MODE_INVALID_VALUE',
    message: `${name}: expected ${expected}, got ${JSON.stringify(value)}`,
    hint,
  };
}

/**
 * Perf mode state from the environment, or null when perf mode is off (no PW_PERF_MODE).
 * Invalid values are errors, never a silent "off" (01-REQ-27); all of them are reported.
 */
export function readModeState(env: ModeEnv): Result<PerfModeState | null, ModeIssue> {
  const mode = read(env, MODE);
  if (mode === undefined) return { ok: true, value: null };

  const issues: ModeIssue[] = [];
  if (mode !== 'test' && mode !== 'thresholds' && mode !== 'check') {
    issues.push(
      invalid(
        MODE,
        '"test", "thresholds" or "check"',
        mode,
        `Set ${MODE} to test, thresholds or check, or unset it to run without perf mode.`,
      ),
    );
  }
  const state: PerfModeState = {
    mode: mode === 'thresholds' || mode === 'check' ? mode : 'test',
  };

  const repeat = read(env, REPEAT);
  if (repeat !== undefined) {
    issues.push({
      code: 'MODE_INVALID_VALUE',
      message: `${REPEAT} is no longer supported, got ${JSON.stringify(repeat)}`,
      hint: `Renamed to ${PASSES}: the test command now runs once per pass. Use ${PASSES}=${repeat}.`,
    });
  }

  const passes = read(env, PASSES);
  if (passes !== undefined) {
    const parsed = parsePasses(passes);
    if (parsed !== null) state.passes = parsed;
    else {
      issues.push(
        invalid(
          PASSES,
          PASSES_FORMAT,
          passes,
          `Fix the number of passes, or unset ${PASSES} to use run.passes from the config.`,
        ),
      );
    }
  }

  const pass = read(env, PASS);
  if (pass !== undefined) {
    const parsed = parsePass(pass);
    if (parsed !== null) state.pass = parsed;
    else {
      issues.push(
        invalid(
          PASS,
          '"k/N" with 2 <= k <= N, like "2/5"',
          pass,
          `${PASS} is set by the package for passes 2 and later; unset it.`,
        ),
      );
    }
  }

  const yes = read(env, YES);
  if (yes !== undefined) {
    if (yes === '1') state.yes = true;
    else {
      issues.push(
        invalid(YES, '"1"', yes, `Set ${YES}=1 to skip the Continue? question, or unset it.`),
      );
    }
  }

  const label = read(env, ENV);
  if (label !== undefined) {
    if (isEnvLabel(label)) state.env = label;
    else {
      issues.push(
        invalid(
          ENV,
          ENV_LABEL_FORMAT,
          label,
          `Fix the environment label, or unset ${ENV} to use run.env from the config.`,
        ),
      );
    }
  }

  const runId = read(env, RUN_ID);
  if (runId !== undefined) state.runId = runId;
  const outcomeFile = read(env, OUTCOME_FILE);
  if (outcomeFile !== undefined) state.outcomeFile = outcomeFile;

  const maxTests = read(env, MAX_TESTS);
  if (maxTests !== undefined) {
    const parsed = parsePasses(maxTests);
    if (parsed !== null && parsed <= 1000) state.maxTests = parsed;
    else {
      issues.push(
        invalid(
          MAX_TESTS,
          'an integer from 1 to 1000, like "10"',
          maxTests,
          `Fix the number of tests a check runs, or unset ${MAX_TESTS} (default ${String(DEFAULT_MAX_TESTS)}).`,
        ),
      );
    }
  }

  const prune = read(env, PRUNE);
  if (prune !== undefined) {
    if (prune === '1') state.prune = true;
    else {
      issues.push(
        invalid(
          PRUNE,
          '"1"',
          prune,
          `Set ${PRUNE}=1 to remove unlocked entries not seen in the run, or unset it.`,
        ),
      );
    }
  }

  return issues.length > 0 ? { ok: false, issues } : { ok: true, value: state };
}

/** Variables for a child process that runs in the given mode (04-REQ-09); unset fields are left out. */
export function writeModeState(state: PerfModeState): Record<string, string> {
  const env: Record<string, string> = { [MODE]: state.mode };
  if (state.passes !== undefined) env[PASSES] = String(state.passes);
  if (state.pass !== undefined)
    env[PASS] = `${String(state.pass.index)}/${String(state.pass.total)}`;
  if (state.yes === true) env[YES] = '1';
  if (state.env !== undefined) env[ENV] = state.env;
  if (state.runId !== undefined) env[RUN_ID] = state.runId;
  if (state.outcomeFile !== undefined) env[OUTCOME_FILE] = state.outcomeFile;
  if (state.prune === true) env[PRUNE] = '1';
  if (state.maxTests !== undefined) env[MAX_TESTS] = String(state.maxTests);
  return env;
}

/** CI detection of the default console reporter (04-REQ-32), the same as Playwright's own. */
export function isCiEnv(env: ModeEnv): boolean {
  return read(env, 'CI') !== undefined;
}

