// Mode contract (01, chapter 4.2): the only place that names and parses the PW_PERF_*
// environment variables (01-REQ-05, 00 chapter 14.1). Pure: the caller passes the environment.
import type { ModeIssue, Result } from '../core/types/index.ts';

export interface PerfModeState {
  /** `check`: a dry run, nothing is evaluated or written (04, chapter 4.11). */
  mode: 'test' | 'thresholds' | 'check';
  /** PW_PERF_MAX_TESTS: measured tests a check runs, 1–1000 (04-REQ-49). */
  maxTests?: number;
  /** PW_PERF_PASSES: passes of the test command (D-39); overrides run.passes.<mode>. */
  passes?: number;
  /** PW_PERF_PASS=k/N: set by the first pass for passes 2…N (04-REQ-64). */
  pass?: { index: number; total: number };
  env?: string;
  /** PW_PERF_RUN_ID: shared by the main process, the workers and passes 2…N (04-REQ-60). */
  runId?: string;
  /** Internal PW_PERF_THRESHOLDS_DIR: thresholds.dir of the wizard's check (04-REQ-58). */
  thresholdsDir?: string;
  /** Internal PW_PERF_MIN_SAMPLES: cap of checks.time.median.minSamples in the wizard's check (04-D-46). */
  minSamples?: number;
  prune?: boolean;
}

export type ModeEnv = Readonly<Record<string, string | undefined>>;

const MODE = 'PW_PERF_MODE';
const PASSES = 'PW_PERF_PASSES';
const PASS = 'PW_PERF_PASS';
/** Replaced by PW_PERF_PASSES (D-39); a set value is an error with a hint. */
const REPEAT = 'PW_PERF_REPEAT';
const ENV = 'PW_PERF_ENV';
const RUN_ID = 'PW_PERF_RUN_ID';
const THRESHOLDS_DIR = 'PW_PERF_THRESHOLDS_DIR';
const MIN_SAMPLES = 'PW_PERF_MIN_SAMPLES';
const PRUNE = 'PW_PERF_PRUNE';
const MAX_TESTS = 'PW_PERF_MAX_TESTS';
/** Variables of the wizard (04, chapter 4.10; D-43). */
const LANG = 'PW_PERF_LANG';
const DRY_RUN = 'PW_PERF_DRY_RUN';
const NO_TUTORIAL = 'PW_PERF_NO_TUTORIAL';

/** Name of the state file of a check in the temporary directory (04-REQ-49). */
export function checkStateFileName(runId: string): string {
  return `playwright-performance-regression-${runId}.check.json`;
}

/** Default of PW_PERF_MAX_TESTS (04-REQ-49). */
export const DEFAULT_MAX_TESTS = 10;

const POSITIVE_INTEGER = /^[1-9][0-9]*$/u;
const ENV_LABEL = /^[a-z0-9-]{1,32}$/u;

/**
 * Number of passes from the text of PW_PERF_PASSES: an integer >= 1, else null. The upper bound
 * comes from the config schema (resolveConfig).
 */
export function parsePasses(text: string): number | null {
  return POSITIVE_INTEGER.test(text) ? Number(text) : null;
}

/** PW_PERF_PASS=k/N with 2 <= k <= N <= 1000 (01, chapter 6), else null. */
export function parsePass(text: string): { index: number; total: number } | null {
  const match = /^([1-9][0-9]*)\/([1-9][0-9]*)$/u.exec(text);
  if (match === null) return null;
  const index = Number(match[1]);
  const total = Number(match[2]);
  return index >= 2 && index <= total && total <= 1000 ? { index, total } : null;
}

/** Whether `text` is a valid environment label (PW_PERF_ENV; D-18). */
export function isEnvLabel(text: string): boolean {
  return ENV_LABEL.test(text);
}

/** Expected format of a repetition count and of an environment label, for messages. */
export const PASSES_FORMAT = 'an integer >= 1, like "5"';
export const ENV_LABEL_FORMAT =
  'a label of lowercase letters, digits and "-" (at most 32 characters), like "staging"';

/**
 * Run id `YYYY-MM-DDTHH-MM-SS-xxxx`: start time in UTC and 4 random hex digits (04-REQ-10).
 * Generated by withPerf() in the main process, or by the reporter without PW_PERF_RUN_ID.
 */
export function generateRunId(date: Date, random: () => number): string {
  const time = date.toISOString().slice(0, 19).replaceAll(':', '-');
  const hex = Math.floor(random() * 0x10000)
    .toString(16)
    .padStart(4, '0');
  return `${time}-${hex}`;
}

/** An empty variable counts as unset (03, chapter 10). */
function read(env: ModeEnv, name: string): string | undefined {
  const value = env[name];
  return value === undefined || value === '' ? undefined : value;
}

function invalid(name: string, expected: string, value: string, hint: string): ModeIssue {
  return {
    code: 'MODE_INVALID_VALUE',
    message: `${name}: expected ${expected}, got ${JSON.stringify(value)}`,
    hint,
  };
}

/**
 * Perf mode state from the environment, or null when perf mode is off (no PW_PERF_MODE).
 * Invalid values are errors, never a silent "off" (01-REQ-27); all of them are reported.
 */
export function readModeState(env: ModeEnv): Result<PerfModeState | null, ModeIssue> {
  const mode = read(env, MODE);
  if (mode === undefined) return { ok: true, value: null };

  const issues: ModeIssue[] = [];
  if (mode !== 'test' && mode !== 'thresholds' && mode !== 'check') {
    issues.push(
      invalid(
        MODE,
        '"test", "thresholds" or "check"',
        mode,
        `Set ${MODE} to test, thresholds or check, or unset it to run without perf mode.`,
      ),
    );
  }
  const state: PerfModeState = {
    mode: mode === 'thresholds' || mode === 'check' ? mode : 'test',
  };

  const repeat = read(env, REPEAT);
  if (repeat !== undefined) {
    issues.push({
      code: 'MODE_INVALID_VALUE',
      message: `${REPEAT} is no longer supported, got ${JSON.stringify(repeat)}`,
      hint: `Renamed to ${PASSES}: the test command now runs once per pass. Use ${PASSES}=${repeat}.`,
    });
  }

  const passes = read(env, PASSES);
  if (passes !== undefined) {
    const parsed = parsePasses(passes);
    if (parsed !== null) state.passes = parsed;
    else {
      issues.push(
        invalid(
          PASSES,
          PASSES_FORMAT,
          passes,
          `Fix the number of passes, or unset ${PASSES} to use run.passes from the config.`,
        ),
      );
    }
  }

  const pass = read(env, PASS);
  if (pass !== undefined) {
    const parsed = parsePass(pass);
    if (parsed !== null) state.pass = parsed;
    else {
      issues.push(
        invalid(
          PASS,
          '"k/N" with 2 <= k <= N, like "2/5"',
          pass,
          `${PASS} is set by the package for passes 2 and later; unset it.`,
        ),
      );
    }
  }

  const label = read(env, ENV);
  if (label !== undefined) {
    if (isEnvLabel(label)) state.env = label;
    else {
      issues.push(
        invalid(
          ENV,
          ENV_LABEL_FORMAT,
          label,
          `Fix the environment label, or unset ${ENV} to use run.env from the config.`,
        ),
      );
    }
  }

  const runId = read(env, RUN_ID);
  if (runId !== undefined) state.runId = runId;
  const thresholdsDir = read(env, THRESHOLDS_DIR);
  if (thresholdsDir !== undefined) state.thresholdsDir = thresholdsDir;
  // Internal (04-D-46): only the wizard sets it, so a value that is not a positive integer is ignored.
  const minSamples = read(env, MIN_SAMPLES);
  const parsedMinSamples = minSamples === undefined ? null : parsePasses(minSamples);
  if (parsedMinSamples !== null) state.minSamples = parsedMinSamples;

  const maxTests = read(env, MAX_TESTS);
  if (maxTests !== undefined) {
    const parsed = parsePasses(maxTests);
    if (parsed !== null && parsed <= 1000) state.maxTests = parsed;
    else {
      issues.push(
        invalid(
          MAX_TESTS,
          'an integer from 1 to 1000, like "10"',
          maxTests,
          `Fix the number of tests a check runs, or unset ${MAX_TESTS} (default ${String(DEFAULT_MAX_TESTS)}).`,
        ),
      );
    }
  }

  const prune = read(env, PRUNE);
  if (prune !== undefined) {
    if (prune === '1') state.prune = true;
    else {
      issues.push(
        invalid(
          PRUNE,
          '"1"',
          prune,
          `Set ${PRUNE}=1 to remove unlocked entries not seen in the run, or unset it.`,
        ),
      );
    }
  }

  return issues.length > 0 ? { ok: false, issues } : { ok: true, value: state };
}

/** Variables for a child process that runs in the given mode (passes, 04-REQ-64); unset fields are left out. */
export function writeModeState(state: PerfModeState): Record<string, string> {
  const env: Record<string, string> = { [MODE]: state.mode };
  if (state.passes !== undefined) env[PASSES] = String(state.passes);
  if (state.pass !== undefined)
    env[PASS] = `${String(state.pass.index)}/${String(state.pass.total)}`;
  if (state.env !== undefined) env[ENV] = state.env;
  if (state.runId !== undefined) env[RUN_ID] = state.runId;
  if (state.thresholdsDir !== undefined) env[THRESHOLDS_DIR] = state.thresholdsDir;
  if (state.minSamples !== undefined) env[MIN_SAMPLES] = String(state.minSamples);
  if (state.prune === true) env[PRUNE] = '1';
  if (state.maxTests !== undefined) env[MAX_TESTS] = String(state.maxTests);
  return env;
}

export interface InitEnv {
  /** PW_PERF_LANG: the wizard language without the question of step 0 (04-REQ-43). */
  lang?: string;
  /** PW_PERF_DRY_RUN=1: only the planned changes, nothing written (04-REQ-37). */
  dryRun: boolean;
  /** PW_PERF_NO_TUTORIAL=1: only the manual setup steps (04-REQ-45). */
  noTutorial: boolean;
}

function readFlag(env: ModeEnv, name: string, hint: string, issues: ModeIssue[]): boolean {
  const value = read(env, name);
  if (value === undefined) return false;
  if (value === '1') return true;
  issues.push(invalid(name, '"1"', value, hint));
  return false;
}

/**
 * The variables of the wizard (04, chapter 4.10; D-43). `languages` are the wizard languages; an
 * unknown PW_PERF_LANG lists them. Invalid values are errors (01-REQ-27), all reported at once.
 */
export function readInitEnv(
  env: ModeEnv,
  languages: readonly string[],
): Result<InitEnv, ModeIssue> {
  const issues: ModeIssue[] = [];
  const state: InitEnv = {
    dryRun: readFlag(
      env,
      DRY_RUN,
      `Set ${DRY_RUN}=1 to only see the planned changes, or unset it.`,
      issues,
    ),
    noTutorial: readFlag(
      env,
      NO_TUTORIAL,
      `Set ${NO_TUTORIAL}=1 to print only the manual setup steps, or unset it.`,
      issues,
    ),
  };
  const lang = read(env, LANG);
  if (lang !== undefined) {
    const code = lang.toLowerCase();
    if (languages.includes(code)) state.lang = code;
    else
      issues.push(
        invalid(
          LANG,
          `one of ${languages.join(', ')}`,
          lang,
          `Set ${LANG} to one of ${languages.join(', ')}, or unset it to choose in the wizard.`,
        ),
      );
  }
  return issues.length > 0 ? { ok: false, issues } : { ok: true, value: state };
}

/** CI detection of the default console reporter (04-REQ-32), the same as Playwright's own. */
export function isCiEnv(env: ModeEnv): boolean {
  return read(env, 'CI') !== undefined;
}

