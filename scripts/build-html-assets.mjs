#!/usr/bin/env node
// @ts-check
// Compiles the HTML report template (11-REQ-24): src/html/template/app.ts is compiled and
// minified to one script, styles.css is minified, and both are written with their SHA-256
// hashes for the Content-Security-Policy (11-REQ-23, 11-D-07) to src/html/generated/assets.ts.
// The output is committed; `pnpm build` runs this script with --check first.
//
// Usage: node scripts/build-html-assets.mjs [--check]
//   --check  do not write; exit 1 when the committed file differs from the generated one
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const templateDir = join(root, 'src/html/template');
const outFile = join(root, 'src/html/generated/assets.ts');
/** Target size of script and styles together, before compression (11-REQ-25). */
const MAX_BYTES = 30 * 1024;

/** @param {string} text */
const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('base64');

/** Normalizes line endings, so a checkout with CRLF gives the same output. */
const read = (/** @type {string} */ name) =>
  readFileSync(join(templateDir, name), 'utf8').replaceAll('\r\n', '\n');

/** @returns {Promise<string>} */
export async function generate() {
  const script = (
    await transform(read('app.ts'), {
      loader: 'ts',
      format: 'iife',
      target: 'es2020',
      minify: true,
      legalComments: 'none',
      charset: 'utf8',
    })
  ).code.trim();
  const styles = (
    await transform(read('styles.css'), {
      loader: 'css',
      minify: true,
      legalComments: 'none',
      charset: 'utf8',
    })
  ).code.trim();
  if (/<\/script|<!--/iu.test(script))
    throw new Error('app.ts compiles to text that ends <script>');
  if (/<\/style/iu.test(styles)) throw new Error('styles.css contains text that ends <style>');
  const size = Buffer.byteLength(script) + Buffer.byteLength(styles);
  if (size > MAX_BYTES) {
    throw new Error(`script and styles are ${size} bytes, more than ${MAX_BYTES} (11-REQ-25)`);
  }
  const source = `// Generated by scripts/build-html-assets.mjs from src/html/template/. Do not edit by hand:
// change the template and run \`pnpm gen:html\` (11-REQ-24).

/** Minified stylesheet of the HTML report. */
export const STYLES = ${JSON.stringify(styles)};

/** Base64 SHA-256 of STYLES for the Content-Security-Policy (11-REQ-23). */
export const STYLES_SHA256 = ${JSON.stringify(sha256(styles))};

/** Compiled and minified script of the HTML report (11, chapter 7). */
export const SCRIPT = ${JSON.stringify(script)};

/** Base64 SHA-256 of SCRIPT for the Content-Security-Policy (11-REQ-23). */
export const SCRIPT_SHA256 = ${JSON.stringify(sha256(script))};
`;
  const options = (await prettier.resolveConfig(outFile)) ?? {};
  return prettier.format(source, { ...options, filepath: outFile });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const text = await generate();
  /** @type {string | null} */
  let current;
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    current = null;
  }
  const name = relative(root, outFile);
  if (check) {
    if (current !== text) {
      console.error(`${name} is out of date: run \`pnpm gen:html\` and commit the result.`);
      process.exit(1);
    }
    console.log(`${name} is up to date.`);
  } else {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, text);
    console.log(`wrote ${name}`);
  }
}
