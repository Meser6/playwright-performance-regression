#!/usr/bin/env node
// @ts-check
// Generates the option list of the pw-perf.config.ts written by the init wizard (04-REQ-46,
// 04-REQ-38 step 7) from schemas/config.schema.json: every option in schema order with its
// default value and a one-sentence English description. The wizard takes the default values and
// the section comments from this list (04-D-54). The output is committed; CI runs this script
// with --check.
//
// Descriptions are sanitized like docs/configuration.md (no specification references, package
// placeholders replaced) and cut to their first sentence.
//
// Usage: node scripts/build-config-template.mjs [--check]
//   --check  do not write; exit 1 when the committed file differs from the generated one
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { listOptions, NOTES, sanitize } from './build-config-docs.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/cli/init/generated/config-options.ts');

/** Options of the JSON config only, not written to pw-perf.config.ts. */
const SKIPPED = new Set(['$schema']);

/** Descriptions for options the schema leaves without one. */
const COMMENT_NOTES = {
  'checks.slowShare.t.api': 'Bounds of the derived T for backend request keys.',
  'checks.slowShare.t.step': 'Bounds of the derived T for test.step keys.',
};

/** Abbreviations whose period does not end a sentence. */
const ABBREVIATIONS = /\b(e\.g|i\.e|etc|vs)\./gu;

/**
 * The first sentence of a description, without Markdown code spans. A period followed by a space
 * or the end ends a sentence, except in "e.g." and similar abbreviations.
 * @param {string} text
 * @returns {string}
 */
export function firstSentence(text) {
  const plain = text
    .replaceAll('`', '')
    .replace(/\s+/gu, ' ')
    .trim()
    .replace(ABBREVIATIONS, (abbr) => abbr.replaceAll('.', '\u0000'));
  const match = /^.*?[.!?](?=\s|$)/u.exec(plain);
  const sentence = (match === null ? plain : match[0]).replaceAll('\u0000', '.');
  return /[.!?]$/u.test(sentence) ? sentence : `${sentence}.`;
}

/**
 * @typedef {{ path: string, description: string, leaf: boolean, default?: unknown }} TemplateOption
 */

/**
 * Every option of the schema in document order with its default: the default of the option, or
 * its entry in the default of the enclosing object (e.g. checks.slowShare.t.api.min).
 * @param {any} schema
 * @returns {TemplateOption[]}
 */
export function templateOptions(schema) {
  /** @type {Map<string, unknown>} */
  const defaults = new Map();
  /** @type {TemplateOption[]} */
  const out = [];
  for (const option of listOptions(schema)) {
    if (SKIPPED.has(option.path)) continue;
    const parentPath = option.path.split('.').slice(0, -1).join('.');
    const name = option.path.split('.').at(-1) ?? '';
    const parentDefault = defaults.get(parentPath);
    /** @type {unknown} */
    let value;
    if (Object.hasOwn(option.node, 'default')) value = option.node.default;
    else if (
      parentDefault !== null &&
      typeof parentDefault === 'object' &&
      Object.hasOwn(parentDefault, name)
    )
      value = /** @type {Record<string, unknown>} */ (parentDefault)[name];
    if (value !== undefined) defaults.set(option.path, value);
    const note = /** @type {Record<string, { description?: string }>} */ (NOTES)[option.path];
    const text =
      /** @type {Record<string, string>} */ (COMMENT_NOTES)[option.path] ??
      note?.description ??
      option.raw.description ??
      option.node.description;
    if (text === undefined) throw new Error(`no description for the option ${option.path}`);
    /** @type {TemplateOption} */
    const entry = {
      path: option.path,
      description: firstSentence(sanitize(text)),
      leaf: option.leaf,
    };
    if (option.leaf && value !== undefined) entry.default = value;
    out.push(entry);
  }
  return out;
}

/** @returns {Promise<string>} */
export async function generate() {
  const schema = JSON.parse(readFileSync(join(root, 'schemas/config.schema.json'), 'utf8'));
  const options = templateOptions(schema);
  const source = `// Generated by scripts/build-config-template.mjs from schemas/config.schema.json. Do not edit
// by hand: change the schema and run \`pnpm gen:config-template\` (04-REQ-46).

export interface TemplateOption {
  /** Dotted option path, e.g. "run.repeat.test". */
  path: string;
  /** One English sentence from the schema description. */
  description: string;
  /** No child options (a value, a list or a map). */
  leaf: boolean;
  /** Default value of a leaf; absent for options without one (keys.keyBuilder). */
  default?: unknown;
}

/** Every option of the package config in schema order, objects before their children. */
export const CONFIG_OPTIONS: readonly TemplateOption[] = ${JSON.stringify(options)};
`;
  const config = (await prettier.resolveConfig(outFile)) ?? {};
  return prettier.format(source, { ...config, filepath: outFile });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const text = await generate();
  /** @type {string | null} */
  let current;
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    current = null;
  }
  const name = relative(root, outFile);
  if (check) {
    if (current !== text) {
      console.error(
        `${name} is out of date: run \`pnpm gen:config-template\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`${name} is up to date.`);
  } else {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, text);
    console.log(`wrote ${name}`);
  }
}
