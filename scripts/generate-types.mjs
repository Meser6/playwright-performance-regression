#!/usr/bin/env node
// @ts-check
// Generates code from the JSON Schemas in schemas/, which are the single source of truth; the
// output is committed:
//   - src/core/types/generated/formats.ts: TypeScript types of the file formats (02-REQ-02,
//     02-D-07);
//   - src/core/config/generated/defaults.ts: DEFAULT_CONFIG, the result of applying the
//     schema's `default` keywords to an empty config (03-REQ-05, 03-D-01).
//
// Usage: node scripts/generate-types.mjs [--check]
//   --check  do not write; exit 1 when a committed file differs from the generated one
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { compile } from 'json-schema-to-typescript';
import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(root, 'schemas');
const outFile = join(root, 'src/core/types/generated/formats.ts');
const defaultsFile = join(root, 'src/core/config/generated/defaults.ts');
const ID_PREFIX = 'https://pkg.invalid/schemas/';
const FORMATS = ['config', 'samples', 'run-report', 'thresholds', 'outcome'];

/** @param {string} name @returns {any} */
const readSchema = (name) => JSON.parse(readFileSync(join(schemaDir, name), 'utf8'));

// A "$ref" to a named type (a whole schema file or a $defs entry) with annotation siblings
// would be emitted as a second copy of that type (e.g. PackageConfig1). Dropping the
// annotations in memory keeps one type per definition; refs to primitive definitions such as
// common.schema.json#/$defs/ms keep their descriptions as field comments.
const ANNOTATIONS = new Set(['description', '$comment', 'title']);
const PRIMITIVE_DEFS = new Set(
  Object.entries(readSchema('common.schema.json').$defs)
    .filter(([, def]) => def.type !== 'object')
    .map(([name]) => `common.schema.json#/$defs/${name}`),
);
/**
 * @param {unknown} node
 * @returns {unknown}
 */
function stripRefAnnotations(node) {
  if (Array.isArray(node)) return node.map(stripRefAnnotations);
  if (node === null || typeof node !== 'object') return node;
  const object = /** @type {Record<string, unknown>} */ (node);
  const keys = Object.keys(object);
  const isAnnotatedRef =
    typeof object.$ref === 'string' &&
    !PRIMITIVE_DEFS.has(object.$ref) &&
    keys.every((k) => k === '$ref' || ANNOTATIONS.has(k));
  return Object.fromEntries(
    keys
      .filter((k) => !(isAnnotatedRef && k !== '$ref'))
      .map((k) => [k, stripRefAnnotations(object[k])]),
  );
}

// Resolve "$id"-based references (https://pkg.invalid/schemas/<name>) to the local files.
const localResolver = {
  order: 1,
  /** @param {{ url: string }} file */
  canRead: (file) => file.url.startsWith(ID_PREFIX),
  /** @param {{ url: string }} file */
  read: (file) => {
    const name = file.url.slice(ID_PREFIX.length).split('#')[0] ?? '';
    return JSON.stringify(stripRefAnnotations(readSchema(name)));
  },
};

/** @type {import('json-schema-to-typescript').JSONSchema} */
const index = {
  $id: `${ID_PREFIX}file-formats.json`,
  title: 'FileFormats',
  description: 'Map of file format name to its type.',
  type: 'object',
  additionalProperties: false,
  required: FORMATS,
  properties: Object.fromEntries(FORMATS.map((n) => [n, { $ref: `${ID_PREFIX}${n}.schema.json` }])),
};

const banner = `// Generated by scripts/generate-types.mjs from schemas/*.schema.json. Do not edit by hand:
// change the schema and run \`pnpm gen:types\` (02-REQ-02).
`;

const raw = await compile(index, 'FileFormats', {
  cwd: schemaDir,
  bannerComment: banner,
  additionalProperties: false,
  format: false,
  $refOptions: { resolve: { local: localResolver } },
});
/**
 * Applies the `default` keywords of config.schema.json to an empty config, the way a JSON Schema
 * validator with defaults does (Ajv `useDefaults`), and checks that the result is valid.
 * @returns {Record<string, unknown>}
 */
function defaultConfig() {
  const ajv = new Ajv2020({ strict: true, strictRequired: false, useDefaults: true });
  for (const file of readdirSync(schemaDir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()) {
    ajv.addSchema(readSchema(file));
  }
  const validate = ajv.getSchema(`${ID_PREFIX}config.schema.json`);
  if (!validate) throw new Error('config.schema.json is not registered');
  /** @type {Record<string, unknown>} */
  const config = {};
  if (!validate(config)) {
    throw new Error(`schema defaults are not a valid config: ${JSON.stringify(validate.errors)}`);
  }
  return config;
}

const defaultsSource = `// Generated by scripts/generate-types.mjs from schemas/config.schema.json. Do not edit by hand:
// change the \`default\` keywords in the schema and run \`pnpm gen:types\` (03-REQ-05).
import type { ResolvedConfigJson } from '../types.ts';

/** The schema's \`default\` keywords applied to an empty config (03-REQ-05, 03-D-01). */
export const DEFAULT_CONFIG: ResolvedConfigJson = ${JSON.stringify(defaultConfig())};
`;

/** @type {[string, string][]} */
const outputs = [];
for (const [file, source] of /** @type {[string, string][]} */ ([
  [outFile, raw],
  [defaultsFile, defaultsSource],
])) {
  const prettierConfig = await prettier.resolveConfig(file);
  outputs.push([file, await prettier.format(source, { ...prettierConfig, filepath: file })]);
}

if (process.argv.includes('--check')) {
  let outdated = false;
  for (const [file, output] of outputs) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // missing file counts as outdated
    }
    if (current !== output) {
      outdated = true;
      console.error(
        `check-types-generated: ${relative(root, file)} is out of date; run \`pnpm gen:types\``,
      );
    }
  }
  if (outdated) process.exit(1);
  console.log('check-types-generated: generated types and defaults are up to date');
} else {
  for (const [file, output] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, output);
    console.log(`generate-types: wrote ${relative(root, file)}`);
  }
}
