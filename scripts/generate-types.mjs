#!/usr/bin/env node
// @ts-check
// Generates TypeScript types for the file formats from the JSON Schemas in schemas/
// (02-REQ-02, 02-D-07). The schemas are the single source of truth; the output is committed.
//
// Usage: node scripts/generate-types.mjs [--check]
//   --check  do not write; exit 1 when the committed file differs from the generated one
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(root, 'schemas');
const outFile = join(root, 'src/core/types/generated/formats.ts');
const ID_PREFIX = 'https://pkg.invalid/schemas/';
const FORMATS = ['config', 'samples', 'run-report', 'thresholds', 'outcome'];

/** @param {string} name @returns {any} */
const readSchema = (name) => JSON.parse(readFileSync(join(schemaDir, name), 'utf8'));

// A "$ref" to a named type (a whole schema file or a $defs entry) with annotation siblings
// would be emitted as a second copy of that type (e.g. PackageConfig1). Dropping the
// annotations in memory keeps one type per definition; refs to primitive definitions such as
// common.schema.json#/$defs/ms keep their descriptions as field comments.
const ANNOTATIONS = new Set(['description', '$comment', 'title']);
const PRIMITIVE_DEFS = new Set(
  Object.entries(readSchema('common.schema.json').$defs)
    .filter(([, def]) => def.type !== 'object')
    .map(([name]) => `common.schema.json#/$defs/${name}`),
);
/**
 * @param {unknown} node
 * @returns {unknown}
 */
function stripRefAnnotations(node) {
  if (Array.isArray(node)) return node.map(stripRefAnnotations);
  if (node === null || typeof node !== 'object') return node;
  const object = /** @type {Record<string, unknown>} */ (node);
  const keys = Object.keys(object);
  const isAnnotatedRef =
    typeof object.$ref === 'string' &&
    !PRIMITIVE_DEFS.has(object.$ref) &&
    keys.every((k) => k === '$ref' || ANNOTATIONS.has(k));
  return Object.fromEntries(
    keys
      .filter((k) => !(isAnnotatedRef && k !== '$ref'))
      .map((k) => [k, stripRefAnnotations(object[k])]),
  );
}

// Resolve "$id"-based references (https://pkg.invalid/schemas/<name>) to the local files.
const localResolver = {
  order: 1,
  /** @param {{ url: string }} file */
  canRead: (file) => file.url.startsWith(ID_PREFIX),
  /** @param {{ url: string }} file */
  read: (file) => {
    const name = file.url.slice(ID_PREFIX.length).split('#')[0] ?? '';
    return JSON.stringify(stripRefAnnotations(readSchema(name)));
  },
};

/** @type {import('json-schema-to-typescript').JSONSchema} */
const index = {
  $id: `${ID_PREFIX}file-formats.json`,
  title: 'FileFormats',
  description: 'Map of file format name to its type.',
  type: 'object',
  additionalProperties: false,
  required: FORMATS,
  properties: Object.fromEntries(FORMATS.map((n) => [n, { $ref: `${ID_PREFIX}${n}.schema.json` }])),
};

const banner = `// Generated by scripts/generate-types.mjs from schemas/*.schema.json. Do not edit by hand:
// change the schema and run \`pnpm gen:types\` (02-REQ-02).
`;

const raw = await compile(index, 'FileFormats', {
  cwd: schemaDir,
  bannerComment: banner,
  additionalProperties: false,
  format: false,
  $refOptions: { resolve: { local: localResolver } },
});
const prettierConfig = await prettier.resolveConfig(outFile);
const output = await prettier.format(raw, { ...prettierConfig, filepath: outFile });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    // missing file counts as outdated
  }
  if (current !== output) {
    console.error(
      'check-types-generated: src/core/types/generated/formats.ts is out of date; run `pnpm gen:types`',
    );
    process.exit(1);
  }
  console.log('check-types-generated: generated types are up to date');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, output);
  console.log('generate-types: wrote src/core/types/generated/formats.ts');
}
