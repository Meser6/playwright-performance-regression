#!/usr/bin/env node
// @ts-check
// Embeds the CI recipes of examples/ci/ in the init wizard (04-REQ-38 step 8, 13-REQ-16,
// 13-D-12): writes them unchanged to src/cli/init/generated/ci-templates.ts. The output is
// committed; CI runs this script with --check, and a contract test compares the strings with the
// files (13-AC-11).
//
// Usage: node scripts/build-ci-templates.mjs [--check]
//   --check  do not write; exit 1 when the committed file differs from the generated one
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/cli/init/generated/ci-templates.ts');

/** CI platform → recipe file in examples/ci/. */
export const RECIPES = {
  github: 'github-actions.yml',
  gitlab: 'gitlab-ci.yml',
  jenkins: 'Jenkinsfile',
  azure: 'azure-pipelines.yml',
};

/** @returns {Promise<string>} */
export async function generate() {
  const entries = Object.entries(RECIPES).map(([platform, file]) => {
    // Line endings normalized, so a checkout with CRLF gives the same output.
    const text = readFileSync(join(root, 'examples/ci', file), 'utf8').replaceAll('\r\n', '\n');
    return `  /** examples/ci/${file} */\n  ${platform}: ${JSON.stringify(text)},`;
  });
  const source = `// Generated by scripts/build-ci-templates.mjs from examples/ci/. Do not edit by hand: change
// the recipe and run \`pnpm gen:ci\` (13-REQ-16, 13-AC-11).

/** CI recipes, byte for byte equal to the files in examples/ci/. */
export const CI_TEMPLATES = {
${entries.join('\n')}
} as const;
`;
  const options = (await prettier.resolveConfig(outFile)) ?? {};
  return prettier.format(source, { ...options, filepath: outFile });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const text = await generate();
  /** @type {string | null} */
  let current;
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    current = null;
  }
  const name = relative(root, outFile);
  if (check) {
    if (current !== text) {
      console.error(`${name} is out of date: run \`pnpm gen:ci\` and commit the result.`);
      process.exit(1);
    }
    console.log(`${name} is up to date.`);
  } else {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, text);
    console.log(`wrote ${name}`);
  }
}
